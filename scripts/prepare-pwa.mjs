import {readdir,readFile,writeFile} from 'node:fs/promises';
import {resolve,relative,sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const digest=buffer=>createHash('sha256').update(buffer).digest('hex');
const canonical=(name,bytes)=>name.endsWith('.png')?bytes:Buffer.from(bytes.toString('utf8').replace(/\r\n/g,'\n'));
const runtime=/\.(?:html|js|css|svg|png|webmanifest)$/i;
export async function createPrecache(root){
  const entries=[];
  async function visit(directory){
    for(const entry of await readdir(directory,{withFileTypes:true})){
      const path=resolve(directory,entry.name);
      if(entry.isDirectory())await visit(path);
      else if(runtime.test(entry.name)&&!['sw.js','precache.js'].includes(entry.name)){
        const name='./'+relative(root,path).split(sep).join('/');
        entries.push([name,digest(canonical(name,await readFile(path)))]);
      }
    }
  }
  await visit(root);entries.sort(([a],[b])=>a.localeCompare(b,'en'));
  if(!entries.some(([name])=>name==='./index.html'))throw Error('离线清单：缺少 dist/index.html');
  const fingerprint=createHash('sha256');
  for(const[name,hash]of entries)fingerprint.update(name+'\0'+hash+'\n');
  fingerprint.update('@worker\0'+digest(canonical('sw.js',await readFile(resolve(root,'sw.js')))));
  return{version:fingerprint.digest('hex').slice(0,20),assets:entries.map(([name])=>name),revisions:Object.fromEntries(entries)};
}
export function renderPrecache(metadata){
  return '// Generated by scripts/prepare-pwa.mjs. Do not edit by hand.\nself.PLAYGROUND_PRECACHE = '+JSON.stringify(metadata,null,2)+';\n';
}
async function main(){
  const root=fileURLToPath(new URL('../dist/',import.meta.url)),path=resolve(root,'precache.js');
  const output=renderPrecache(await createPrecache(root));
  if(process.argv.includes('--check')){
    let current='';try{current=await readFile(path,'utf8');}catch{}
    if(current.replace(/\r\n/g,'\n')!==output)throw Error('离线清单已过期：请先运行 npm run prepare:pwa，再重新检查或发布。');
    console.log('PWA precache manifest is current.');
  }else{
    await writeFile(path,output);console.log('Prepared the complete offline game collection.');
  }
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))main().catch(error=>{console.error(error.message);process.exitCode=1;});
